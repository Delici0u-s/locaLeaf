// Builds config/texlive-files.json.gz: file name → TeX Live package, for the files TeX looks up at run time
// (tex/, fonts/{opentype,truetype,tfm,type1,vf,enc,map}, bibtex/bst). Read from texlive.tlpdb in the TeX Live
// Docker image. The engine uses it to fetch a package from a CTAN mirror when a file isn't available otherwise.
// Usage: node scripts/build-texlive-index.mjs [image]
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { gzipSync } from 'node:zlib'
import { ROOT } from './lib.mjs'

const image = process.argv[2] ?? 'texlive/texlive:latest'
const awk = 'awk \'/^name /{p=$2} /^runfiles/{r=1;next} /^[a-z]/{r=0} r&&/^ /{print p"\\t"$1}\' /usr/local/texlive/*/tlpkg/texlive.tlpdb; tex --version | head -1'
const out = execFileSync('docker', ['run', '--rm', image, 'sh', '-c', awk], { encoding: 'utf8', maxBuffer: 1 << 28 })
const lines = out.trim().split('\n')
const texVersion = lines.pop()
const RELEVANT = /texmf-dist\/(tex|fonts\/(opentype|truetype|tfm|type1|vf|enc|map)|bibtex\/bst)\//
const files = {}
for (const line of lines) {
  const [pkg, path] = line.split('\t')
  if (!path || !RELEVANT.test(path) || pkg.includes('.')) continue // "pkg.ARCH" entries are binaries
  const name = path.slice(path.lastIndexOf('/') + 1)
  files[name] ??= pkg
}
const index = { $comment: `Generated by scripts/build-texlive-index.mjs from ${image} (${texVersion}).`, files }
const target = join(ROOT, 'config/texlive-files.json.gz')
writeFileSync(target, gzipSync(JSON.stringify(index), { level: 9 }))
console.log(`${Object.keys(files).length} files → ${target}`)
