// Builds config/font-index.json: font family/full/PostScript names → font file names, for every
// OpenType/TrueType font in TeX Live (read with fc-scan from the TeX Live Docker image).
// The engine uses it to fetch fonts that fontspec asks for by name. Usage: node scripts/build-font-index.mjs [image]
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT } from './lib.mjs'

const image = process.argv[2] ?? 'texlive/texlive:latest'
const script = `find /usr/local/texlive/*/texmf-dist/fonts/opentype /usr/local/texlive/*/texmf-dist/fonts/truetype -type f \\( -name '*.otf' -o -name '*.ttf' -o -name '*.ttc' \\) -print0 | xargs -0 fc-scan --format '%{family}\\t%{style}\\t%{fullname}\\t%{postscriptname}\\t%{file}\\n'; tex --version | head -1`
const out = execFileSync('docker', ['run', '--rm', image, 'sh', '-c', script], { encoding: 'utf8', maxBuffer: 1 << 28 })
const lines = out.trim().split('\n')
const texVersion = lines.pop()

// Faces fontspec loads for a family name: upright, bold, italic, bold italic.
const STANDARD = /^(regular|book|roman|normal|medium|bold|italic|oblique|bolditalic|boldoblique)$/
const norm = s => s.toLowerCase().replace(/[\s_-]+/g, '')
const familyFiles = new Map() // family key → [{file, style}]
const names = new Map() // full / PostScript name key → Set(file)
for (const line of lines) {
  const [family, style, fullname, psname, file] = line.split('\t')
  if (!file) continue
  const base = file.slice(file.lastIndexOf('/') + 1)
  const fams = family.split(',').map(s => s.trim()).filter(Boolean)
  for (const f of fams) {
    const k = norm(f)
    if (!familyFiles.has(k)) familyFiles.set(k, [])
    familyFiles.get(k).push({ file: base, style: norm(style.split(',')[0] ?? '') })
  }
  for (const n of [...fullname.split(','), psname]) {
    if (!n?.trim()) continue
    const k = norm(n)
    if (!names.has(k)) names.set(k, new Set())
    names.get(k).add(base)
  }
}
// A family name maps to its standard faces (or all its files if it has none of them).
for (const [k, files] of familyFiles) {
  const standard = files.filter(f => STANDARD.test(f.style)).map(f => f.file)
  const set = names.get(k) ?? new Set()
  for (const f of standard.length ? standard : files.map(f => f.file)) set.add(f)
  names.set(k, set)
}
const index = {
  $comment: `Generated by scripts/build-font-index.mjs from ${image} (${texVersion}). Keys: font names lowercased without spaces/dashes/underscores; values: the font files to fetch.`,
  names: Object.fromEntries([...names].sort().map(([k, v]) => [k, [...v].sort()])),
}
const file = join(ROOT, 'config/font-index.json')
writeFileSync(file, JSON.stringify(index) + '\n')
console.log(`${names.size} names → ${file}`)
